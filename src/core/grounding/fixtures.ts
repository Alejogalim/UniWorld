import type { UniversityRecord } from './types';

let counter = 0;

export function record(
  partial: Partial<UniversityRecord> & Pick<UniversityRecord, 'name' | 'country_code'>,
): UniversityRecord {
  counter++;
  const id = partial.ror_id ?? `https://ror.org/0${String(counter).padStart(8, '0')}`;
  return {
    ror_id: id,
    name: partial.name,
    aliases: partial.aliases ?? [],
    acronyms: partial.acronyms ?? [],
    country_code: partial.country_code,
    country_name: partial.country_name ?? partial.country_code,
    continent: partial.continent ?? null,
    city: partial.city ?? null,
    lat: partial.lat ?? null,
    lng: partial.lng ?? null,
    website: partial.website ?? null,
    domains: partial.domains ?? [],
  };
}

